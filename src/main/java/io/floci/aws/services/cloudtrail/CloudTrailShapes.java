package io.floci.aws.services.cloudtrail;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import io.floci.aws.core.common.AwsQueryLists;
import io.floci.aws.core.common.VendoredResources;
import io.floci.aws.core.common.XmlParser;
import jakarta.ws.rs.core.MultivaluedMap;

import java.math.BigDecimal;
import java.math.BigInteger;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.regex.Pattern;

/**
 * A service's request and result shapes as a CloudTrail record writes them, read once from the
 * vendored {@code aws/<service>-cloudtrail-shapes.json}.
 *
 * <p>Each file is generated by {@code tools/aws/regen_<service>_cloudtrail_shapes.py} from botocore's
 * model of the service, through the shape walk every vendored shape file shares: every operation's
 * input shape ({@code operations}), its output shape and the element its result is wrapped in
 * ({@code results}), every shape they reach with its type and whether the model marks it
 * {@code sensitive}, and the code each modeled error answers with ({@code errors}). A
 * member is named with a lower first letter ({@code userName}, {@code tags: [{"key", "value"}]}),
 * a number, a boolean or a timestamp is written as one because its shape says so, and a sensitive
 * member is left out, or written as the text a service's records give it ({@link QueryStyle}). A
 * list the model names the members of is read from a Query request under that name
 * ({@code ValuesToAdd.AttributeValue.1}). A Query request ({@code IAM}) is read from its form
 * parameters and its XML result, a JSON one ({@code SQS}) from its body and its result, a map keeping its keys as sent.
 * {@code make aws-data-check} fails when a file is stale against the pinned botocore.
 *
 * <p>A missing or malformed resource is a build defect, not a runtime condition, so loading fails
 * with {@link IllegalStateException}.
 */
public final class CloudTrailShapes {

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Pattern INTEGER = Pattern.compile("[+-]?\\d+");

    /**
     * A timestamp as CloudTrail writes one in an IAM record's {@code responseElements}, as the IAM
     * events of the CloudTrail log file examples do ({@code "createDate": "Jul 19, 2023 9:25:09 PM"},
     * https://docs.aws.amazon.com/awscloudtrail/latest/userguide/cloudtrail-log-file-examples.html).
     */
    private static final DateTimeFormatter RECORD_TIMESTAMP =
            DateTimeFormatter.ofPattern("MMM d, yyyy h:mm:ss a", Locale.US).withZone(ZoneOffset.UTC);

    private static final Map<String, CloudTrailShapes> LOADED = new ConcurrentHashMap<>();

    private final JsonNode operations;
    private final JsonNode results;
    private final JsonNode shapes;
    private final JsonNode errors;

    private CloudTrailShapes(String resourceName, JsonNode model) {
        this.operations = model.path("operations");
        this.results = model.path("results");
        this.shapes = model.path("shapes");
        this.errors = model.path("errors");
        if (!operations.isObject() || operations.isEmpty() || !results.isObject() || results.isEmpty()
                || !shapes.isObject() || shapes.isEmpty()) {
            throw new IllegalStateException(resourceName + " carries no operations, no results or no shapes");
        }
    }

    /** The shapes of {@code service}, the name its file is vendored under ({@code iam}). */
    public static CloudTrailShapes of(String service) {
        return LOADED.computeIfAbsent(service, name -> {
            String resourceName = "aws/" + name + "-cloudtrail-shapes.json";
            return VendoredResources.read(resourceName, name + " CloudTrail shapes",
                    in -> new CloudTrailShapes(resourceName, MAPPER.readTree(in)));
        });
    }

    /**
     * The members {@code params} carries for {@code operation}, without the sensitive ones; null for
     * an operation the model does not carry and for a request that carries none of its members.
     */
    public ObjectNode requestParameters(String operation, MultivaluedMap<String, String> params) {
        return requestParameters(operation, params, QueryStyle.AS_SENT);
    }

    /** As {@link #requestParameters(String, MultivaluedMap)}, written in {@code style}. */
    public ObjectNode requestParameters(String operation, MultivaluedMap<String, String> params, QueryStyle style) {
        JsonNode input = shapes.path(operations.path(operation).asText(""));
        if (!input.has("members")) {
            return null;
        }
        ObjectNode read = readStructure(input, "", params, style);
        return read.isEmpty() ? null : read;
    }

    /**
     * The result {@code xml} answers {@code operation} with, without the sensitive members; null
     * for an operation whose result the model does not wrap and for a result that carries nothing.
     */
    public ObjectNode result(String operation, String xml) {
        return result(operation, xml, QueryStyle.AS_SENT);
    }

    /** As {@link #result(String, String)}, written in {@code style}. */
    public ObjectNode result(String operation, String xml, QueryStyle style) {
        JsonNode entry = results.path(operation);
        String wrapper = entry.path("resultWrapper").asText("");
        if (wrapper.isEmpty()) {
            return null;
        }
        XmlParser.XmlElement result = XmlParser.extractElementTree(xml, wrapper);
        if (result == null) {
            return null;
        }
        String output = entry.path("shape").asText();
        JsonNode read = readElement(output, result, style);
        if (style.loneStructureUnwrapped()) {
            JsonNode members = shapes.path(output).path("members");
            if (members.size() == 1) {
                Map.Entry<String, JsonNode> lone = members.properties().iterator().next();
                if ("structure".equals(shapes.path(lone.getValue().asText()).path("type").asText())) {
                    read = read == null ? null : read.get(lowerFirst(lone.getKey()));
                }
            }
        }
        return read instanceof ObjectNode object && !object.isEmpty() ? object : null;
    }

    /**
     * How a service's CloudTrail records write the members of a Query call, where they differ from the
     * call as sent: {@code sensitiveValue}, when set, writes a member the model marks sensitive as that
     * text rather than leaving it out, and {@code loneStructureUnwrapped} writes a result whose one member
     * is a structure as that structure's own members.
     */
    public record QueryStyle(String sensitiveValue, boolean loneStructureUnwrapped) {
        /** The members as the call carried them, without the sensitive ones. */
        public static final QueryStyle AS_SENT = new QueryStyle(null, false);
    }

    /**
     * The EC2 result {@code xml} answers {@code operation} with, as an EC2 record's
     * {@code responseElements} writes it: each member under its XML name ({@code instancesSet}), a
     * list as {@code {"items": [...]}} and an empty one as {@code {}}, a boolean result
     * ({@code return}) as {@code _return}, the answer's {@code requestId}, a timestamp in epoch
     * milliseconds, and a sensitive member as {@code "<sensitiveDataRemoved>"}, as 2024 records of
     * RunInstances, TerminateInstances, AuthorizeSecurityGroupIngress and ModifyInstanceAttribute
     * write them. A network interface's {@code privateIpAddressesSet} keeps its {@code item} key,
     * as the RunInstances record does. An answer's {@code return} the model does not give, as for
     * ModifyInstanceAttribute (no output) and CreateSecurityGroup, is written {@code "_return": true}
     * all the same, as their records write it.
     */
    public ObjectNode ec2Result(String operation, String xml) {
        String output = results.path(operation).path("shape").asText("");
        XmlParser.XmlElement root = xml == null ? null : XmlParser.extractElementTree(xml, operation + "Response");
        if (root == null) {
            return null;
        }
        ObjectNode read = MAPPER.createObjectNode();
        JsonNode members = shapes.path(output).path("members");
        for (XmlParser.XmlElement child : root.children()) {
            if ("requestId".equals(child.name())) {
                read.put("requestId", child.text());
                continue;
            }
            if ("return".equals(child.name()) && !members.has("return")) {
                read.put("_return", Boolean.parseBoolean(child.text().trim()));
                continue;
            }
            JsonNode member = members.path(child.name());
            JsonNode value = member.isTextual() ? readEc2(member.asText(), child) : null;
            if (value != null) {
                read.set("return".equals(child.name()) ? "_return" : child.name(), value);
            }
        }
        return read.isEmpty() ? null : read;
    }

    private JsonNode readEc2(String shapeName, XmlParser.XmlElement element) {
        JsonNode shape = shapes.path(shapeName);
        if (shape.path("sensitive").asBoolean()) {
            return MAPPER.getNodeFactory().textNode("<sensitiveDataRemoved>");
        }
        return switch (shape.path("type").asText()) {
            case "structure" -> {
                ObjectNode read = MAPPER.createObjectNode();
                JsonNode members = shape.path("members");
                for (XmlParser.XmlElement child : element.children()) {
                    JsonNode member = members.path(child.name());
                    JsonNode value = member.isTextual() ? readEc2(member.asText(), child) : null;
                    if (value != null) {
                        read.set("return".equals(child.name()) ? "_return" : child.name(), value);
                    }
                }
                yield read;
            }
            case "list" -> {
                ArrayNode items = MAPPER.createArrayNode();
                for (XmlParser.XmlElement child : element.children()) {
                    JsonNode value = readEc2(shape.path("member").asText(), child);
                    if (value != null) {
                        items.add(value);
                    }
                }
                ObjectNode read = MAPPER.createObjectNode();
                if (!items.isEmpty()) {
                    read.set("privateIpAddressesSet".equals(element.name()) ? "item" : "items", items);
                }
                yield read;
            }
            case "timestamp" -> {
                try {
                    yield MAPPER.getNodeFactory().numberNode(Instant.parse(element.text().trim()).toEpochMilli());
                } catch (DateTimeParseException expected) {
                    yield MAPPER.getNodeFactory().textNode(element.text());
                }
            }
            default -> element.text().isEmpty() ? null : scalar(shape.path("type").asText(), element.rawText(), false);
        };
    }

    /** The name of the error shape that answers {@code code}; a code IAM does not model is kept. */
    /** The name of the error shape that answers {@code code}; a code the service does not model is kept. */
    public String recordedErrorCode(String code) {
        return code == null ? null : errors.path(code).asText(code);
    }

    /**
     * The members a JSON {@code request} body carries for {@code operation}, without the sensitive
     * ones; null for an operation the model does not carry and for a request that carries none of
     * its members.
     */
    public ObjectNode requestParameters(String operation, JsonNode request) {
        return requestParameters(operation, request, JsonStyle.AS_SENT);
    }

    /** As {@link #requestParameters(String, JsonNode)}, written in {@code style}. */
    public ObjectNode requestParameters(String operation, JsonNode request, JsonStyle style) {
        return readJsonStructure(operations.path(operation).asText(""), request, style);
    }

    /**
     * As {@link #requestParameters(String, JsonNode, JsonStyle)}, for a REST-JSON request: the members the
     * model locates in the path are read from {@code labels}, by the name the route gives them, and those it
     * locates in the query from {@code query}, typed as their shapes type them, ahead of the members of
     * {@code body}. A member it locates in a header is not read.
     */
    public ObjectNode requestParameters(String operation, Map<String, String> labels,
                                        MultivaluedMap<String, String> query, JsonNode body, JsonStyle style) {
        String input = operations.path(operation).asText("");
        JsonNode shape = shapes.path(input);
        ObjectNode request = MAPPER.createObjectNode();
        for (Map.Entry<String, JsonNode> located : shape.path("locations").properties()) {
            String name = located.getValue().path("name").asText();
            String memberShape = shape.path("members").path(located.getKey()).asText();
            JsonNode value = switch (located.getValue().path("location").asText()) {
                case "uri" -> labels == null || labels.get(name) == null ? null
                        : scalar(shapes.path(memberShape).path("type").asText(), labels.get(name), false);
                case "querystring" -> queryValue(memberShape, query == null ? null : query.get(name));
                default -> null;
            };
            if (value != null) {
                request.set(located.getKey(), value);
            }
        }
        if (body != null && body.isObject()) {
            for (Map.Entry<String, JsonNode> member : body.properties()) {
                if (!request.has(member.getKey())) {
                    request.set(member.getKey(), member.getValue());
                }
            }
        }
        return readJsonStructure(input, request, style);
    }

    /** A query member's values, a list when its shape is one, else its first value as its shape types it. */
    private JsonNode queryValue(String shapeName, List<String> values) {
        if (values == null || values.isEmpty()) {
            return null;
        }
        JsonNode shape = shapes.path(shapeName);
        if (!"list".equals(shape.path("type").asText())) {
            return scalar(shape.path("type").asText(), values.getFirst(), false);
        }
        ArrayNode list = MAPPER.createArrayNode();
        String elementType = shapes.path(shape.path("member").asText()).path("type").asText();
        for (String value : values) {
            list.add(scalar(elementType, value, false));
        }
        return list;
    }

    /**
     * The JSON {@code result} {@code operation} answered with, without the sensitive members; null
     * for an operation without a result and for a result that carries nothing.
     */
    public ObjectNode result(String operation, JsonNode result) {
        return result(operation, result, JsonStyle.AS_SENT);
    }

    /** As {@link #result(String, JsonNode)}, written in {@code style}. */
    public ObjectNode result(String operation, JsonNode result, JsonStyle style) {
        return readJsonStructure(results.path(operation).path("shape").asText(""), result, style);
    }

    /**
     * How a service's CloudTrail records write the members of a JSON call, where they differ from
     * the call as sent: {@code omitBlobs} leaves out every binary member (KMS records no ciphertext,
     * import token or signature), and {@code timestamps}, when set, writes a timestamp member in that
     * format rather than as the epoch seconds sent.
     */
    public record JsonStyle(boolean omitBlobs, DateTimeFormatter timestamps) {
        /** The members as the call carried them. */
        public static final JsonStyle AS_SENT = new JsonStyle(false, null);
    }

    private ObjectNode readJsonStructure(String shapeName, JsonNode value, JsonStyle style) {
        if (shapeName.isEmpty() || value == null || !value.isObject()) {
            return null;
        }
        JsonNode read = readJson(shapeName, value, style);
        return read instanceof ObjectNode object && !object.isEmpty() ? object : null;
    }

    private JsonNode readJson(String shapeName, JsonNode value, JsonStyle style) {
        JsonNode shape = shapes.path(shapeName);
        if (value == null || value.isNull() || shape.path("sensitive").asBoolean()) {
            return null;
        }
        return switch (shape.path("type").asText()) {
            case "blob" -> style.omitBlobs() ? null : value;
            case "timestamp" -> style.timestamps() == null ? value : jsonTimestamp(value, style.timestamps());
            case "structure" -> {
                if (!value.isObject()) {
                    yield null;
                }
                ObjectNode read = MAPPER.createObjectNode();
                JsonNode members = shape.path("members");
                for (Map.Entry<String, JsonNode> member : value.properties()) {
                    JsonNode memberShape = members.path(member.getKey());
                    JsonNode memberValue = memberShape.isTextual()
                            ? readJson(memberShape.asText(), member.getValue(), style) : null;
                    if (memberValue != null) {
                        read.set(lowerFirst(member.getKey()), memberValue);
                    }
                }
                yield read;
            }
            case "list" -> {
                if (!value.isArray()) {
                    yield null;
                }
                ArrayNode read = MAPPER.createArrayNode();
                for (JsonNode element : value) {
                    JsonNode elementValue = readJson(shape.path("member").asText(), element, style);
                    if (elementValue != null) {
                        read.add(elementValue);
                    }
                }
                yield read;
            }
            case "map" -> {
                if (!value.isObject()) {
                    yield null;
                }
                ObjectNode read = MAPPER.createObjectNode();
                for (Map.Entry<String, JsonNode> entry : value.properties()) {
                    JsonNode entryValue = readJson(shape.path("value").asText(), entry.getValue(), style);
                    read.set(entry.getKey(), entryValue == null ? MAPPER.nullNode() : entryValue);
                }
                yield read;
            }
            default -> value.isValueNode() ? value : null;
        };
    }

    private ObjectNode readStructure(JsonNode structure, String prefix, MultivaluedMap<String, String> params,
                                     QueryStyle style) {
        ObjectNode read = MAPPER.createObjectNode();
        for (Map.Entry<String, JsonNode> member : structure.path("members").properties()) {
            JsonNode value = readParameter(member.getValue().asText(), prefix + member.getKey(), params, style);
            if (value != null) {
                read.set(lowerFirst(member.getKey()), value);
            }
        }
        return read;
    }

    private JsonNode readParameter(String shapeName, String param, MultivaluedMap<String, String> params,
                                   QueryStyle style) {
        JsonNode shape = shapes.path(shapeName);
        if (shape.path("sensitive").asBoolean()) {
            boolean sent = params.containsKey(param)
                    || params.keySet().stream().anyMatch(key -> key.startsWith(param + "."));
            return style.sensitiveValue() == null || !sent ? null
                    : MAPPER.getNodeFactory().textNode(style.sensitiveValue());
        }
        return switch (shape.path("type").asText()) {
            case "structure" -> {
                if (params.keySet().stream().noneMatch(key -> key.startsWith(param + "."))) {
                    yield null;
                }
                ObjectNode read = readStructure(shape, param + ".", params, style);
                yield read.isEmpty() ? null : read;
            }
            case "list" -> {
                // A list the model names the members of is numbered under that name (ValuesToAdd.AttributeValue.1).
                List<AwsQueryLists.IndexedMember> members = AwsQueryLists.members(params, param,
                        shape.path("memberName").asText(null));
                if (members.isEmpty()) {
                    yield null;
                }
                ArrayNode read = MAPPER.createArrayNode();
                for (AwsQueryLists.IndexedMember member : members) {
                    JsonNode value = readParameter(shape.path("member").asText(), member.prefix(), params, style);
                    if (value != null) {
                        read.add(value);
                    }
                }
                yield read;
            }
            case "map" -> {
                List<AwsQueryLists.IndexedMember> entries = AwsQueryLists.members(params, param, "entry");
                if (entries.isEmpty()) {
                    yield null;
                }
                ObjectNode read = MAPPER.createObjectNode();
                for (AwsQueryLists.IndexedMember entry : entries) {
                    String key = params.getFirst(entry.prefix() + ".key");
                    if (key != null) {
                        JsonNode value = readParameter(shape.path("value").asText(), entry.prefix() + ".value", params,
                                style);
                        read.set(key, value == null ? MAPPER.nullNode() : value);
                    }
                }
                yield read;
            }
            default -> scalar(shape.path("type").asText(), params.getFirst(param), false);
        };
    }

    private JsonNode readElement(String shapeName, XmlParser.XmlElement element, QueryStyle style) {
        JsonNode shape = shapes.path(shapeName);
        if (shape.path("sensitive").asBoolean()) {
            return style.sensitiveValue() == null ? null : MAPPER.getNodeFactory().textNode(style.sensitiveValue());
        }
        return switch (shape.path("type").asText()) {
            case "structure" -> {
                ObjectNode read = MAPPER.createObjectNode();
                JsonNode members = shape.path("members");
                for (XmlParser.XmlElement child : element.children()) {
                    JsonNode member = members.path(child.name());
                    JsonNode value = member.isTextual() ? readElement(member.asText(), child, style) : null;
                    if (value != null) {
                        read.set(lowerFirst(child.name()), value);
                    }
                }
                yield read;
            }
            case "list" -> {
                ArrayNode read = MAPPER.createArrayNode();
                for (XmlParser.XmlElement child : element.children()) {
                    JsonNode value = readElement(shape.path("member").asText(), child, style);
                    if (value != null) {
                        read.add(value);
                    }
                }
                yield read;
            }
            case "map" -> {
                ObjectNode read = MAPPER.createObjectNode();
                for (XmlParser.XmlElement entry : element.children()) {
                    XmlParser.XmlElement key = entry.child("key");
                    XmlParser.XmlElement value = entry.child("value");
                    if (key != null) {
                        JsonNode entryValue = value == null ? null : readElement(shape.path("value").asText(), value,
                                style);
                        read.set(key.text(), entryValue == null ? MAPPER.nullNode() : entryValue);
                    }
                }
                yield read;
            }
            default -> element.text().isEmpty() ? null : scalar(shape.path("type").asText(), element.rawText(), true);
        };
    }

    /**
     * A scalar as its shape types it; a value that does not read as its type is kept as the text
     * sent. A timestamp is rewritten only in a result, as CloudTrail writes one there.
     */
    private static JsonNode scalar(String type, String value, boolean inResult) {
        if (value == null) {
            return null;
        }
        String trimmed = value.trim();
        switch (type) {
            case "integer", "long" -> {
                if (INTEGER.matcher(trimmed).matches()) {
                    return MAPPER.getNodeFactory().numberNode(new BigInteger(trimmed));
                }
            }
            case "double", "float" -> {
                try {
                    return MAPPER.getNodeFactory().numberNode(new BigDecimal(trimmed));
                } catch (NumberFormatException expected) {
                    // Not a number: kept as the text sent.
                }
            }
            case "boolean" -> {
                if ("true".equals(trimmed) || "false".equals(trimmed)) {
                    return MAPPER.getNodeFactory().booleanNode(Boolean.parseBoolean(trimmed));
                }
            }
            case "timestamp" -> {
                if (inResult) {
                    try {
                        return MAPPER.getNodeFactory().textNode(RECORD_TIMESTAMP.format(Instant.parse(trimmed)));
                    } catch (DateTimeParseException expected) {
                        // Not an ISO 8601 instant: kept as the text sent.
                    }
                }
            }
            default -> {
                // A string or a blob is written as sent.
            }
        }
        return MAPPER.getNodeFactory().textNode(value);
    }

    /** A JSON timestamp (epoch seconds, or an ISO 8601 string) in {@code format}; kept as sent otherwise. */
    private static JsonNode jsonTimestamp(JsonNode value, DateTimeFormatter format) {
        try {
            Instant instant = value.isNumber()
                    ? Instant.ofEpochMilli(Math.round(value.asDouble() * 1000))
                    : Instant.parse(value.asText());
            return MAPPER.getNodeFactory().textNode(format.format(instant));
        } catch (DateTimeParseException expected) {
            return value;
        }
    }

    private static String lowerFirst(String name) {
        return name.isEmpty() ? name : Character.toLowerCase(name.charAt(0)) + name.substring(1);
    }
}
