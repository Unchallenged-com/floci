package io.floci.aws.services.cloudtrail;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.floci.aws.core.common.VendoredResources;

import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Which of a service's calls CloudTrail records as management events, which of them are
 * read-only, and the name a record gives a call where it is not the call's own (Lambda's
 * {@code CreateFunction20150331}), read once from the vendored
 * {@code aws/<service>-cloudtrail-events.json}.
 *
 * <p>The file is generated by {@code tools/aws/regen_cloudtrail_events.py}: the management events
 * are the service guide's list, the read-only ones those AWS's Service Reference gives no Write,
 * Permissions management or Tagging access level. A missing or malformed resource is a build
 * defect, not a runtime condition, so loading fails with {@link IllegalStateException}.
 */
public final class CloudTrailEventCatalog {

    private static final Map<String, CloudTrailEventCatalog> LOADED = new ConcurrentHashMap<>();

    private final Set<String> managementEvents;
    private final Set<String> readOnlyActions;
    private final Map<String, String> eventNames;

    private CloudTrailEventCatalog(Set<String> managementEvents, Set<String> readOnlyActions,
                                   Map<String, String> eventNames) {
        this.managementEvents = managementEvents;
        this.readOnlyActions = readOnlyActions;
        this.eventNames = eventNames;
    }

    /** The catalog of {@code service}, as its credential scope names it ({@code sqs}, {@code secretsmanager}). */
    public static CloudTrailEventCatalog of(String service) {
        return LOADED.computeIfAbsent(service, name -> {
            String resource = "aws/" + name + "-cloudtrail-events.json";
            return VendoredResources.read(resource, name + " CloudTrail events",
                    in -> parse(resource, new ObjectMapper().readTree(in)));
        });
    }

    /** Whether CloudTrail records {@code action} as a management event. */
    public boolean isManagementEvent(String action) {
        return action != null && managementEvents.contains(action);
    }

    /** Whether CloudTrail records {@code action} as read-only. */
    public boolean isReadOnly(String action) {
        return action != null && readOnlyActions.contains(action);
    }

    /** The {@code eventName} a record gives {@code action}: its own name unless the file names it otherwise. */
    public String eventName(String action) {
        return eventNames.getOrDefault(action, action);
    }

    private static CloudTrailEventCatalog parse(String resource, JsonNode root) {
        Set<String> events = names(root.path("managementEvents"));
        if (events.isEmpty()) {
            throw new IllegalStateException(resource + " carries no managementEvents");
        }
        Set<String> readOnly = names(root.path("readOnlyActions"));
        if (!events.containsAll(readOnly)) {
            throw new IllegalStateException(resource + " lists a read-only action that is not a management event");
        }
        Map<String, String> eventNames = new HashMap<>();
        for (Map.Entry<String, JsonNode> entry : root.path("eventNames").properties()) {
            if (!events.contains(entry.getKey())) {
                throw new IllegalStateException(resource + " names an event that is not a management event");
            }
            eventNames.put(entry.getKey(), entry.getValue().asText());
        }
        return new CloudTrailEventCatalog(Set.copyOf(events), Set.copyOf(readOnly), Map.copyOf(eventNames));
    }

    private static Set<String> names(JsonNode array) {
        Set<String> names = new HashSet<>();
        for (JsonNode name : array) {
            names.add(name.asText());
        }
        return names;
    }
}
