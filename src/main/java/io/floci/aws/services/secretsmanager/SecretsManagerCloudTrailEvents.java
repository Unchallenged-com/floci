package io.floci.aws.services.secretsmanager;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import io.floci.aws.core.common.AccountResolver;
import io.floci.aws.core.common.AwsErrorResponse;
import io.floci.aws.core.common.AwsException;
import io.floci.aws.core.common.RequestSourceAddress;
import io.floci.aws.core.common.ServicePrincipals;
import io.floci.aws.services.cloudtrail.CloudTrailEventCatalog;
import io.floci.aws.services.cloudtrail.CloudTrailService;
import io.floci.aws.services.cloudtrail.CloudTrailShapes;
import io.floci.aws.services.cloudtrail.ManagementEventSource;
import io.quarkus.vertx.http.runtime.CurrentVertxRequest;
import io.vertx.core.http.HttpServerRequest;
import io.vertx.ext.web.RoutingContext;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import jakarta.ws.rs.core.Response;
import org.jboss.logging.Logger;


/**
 * Records Secrets Manager's calls as CloudTrail management events: "AWS Secrets Manager writes
 * entries to your AWS CloudTrail log for all Secrets Manager operations"
 * (https://docs.aws.amazon.com/secretsmanager/latest/userguide/cloudtrail_log_entries.html). Which
 * calls those are, and which of them are read-only, is the vendored
 * {@code aws/secretsmanager-cloudtrail-events.json} ({@link CloudTrailEventCatalog}): the guide's
 * list, and AWS's Service Reference's access level ({@code GetSecretValue}, {@code ListSecrets} and
 * the other reads are read-only).
 *
 * <p>A call is recorded whether it succeeds, fails, or is refused by IAM enforcement, a trail or not,
 * since event history keeps every management event.
 * {@code requestParameters} and {@code responseElements} are the request's and the result's members
 * named with a lower first letter ({@code secretId}, {@code filters: [{"key", "values"}]}), typed as
 * botocore's Secrets Manager model types them ({@link CloudTrailShapes}), as a 2024 record of
 * {@code ListSecrets} shows them ({@code "maxResults": 100}). A member the model marks sensitive is
 * left out: the API Reference says of {@code SecretString} and {@code SecretBinary} "This field
 * contains sensitive information, so the service does not include it in AWS CloudTrail log
 * entries" (https://docs.aws.amazon.com/secretsmanager/latest/apireference/API_GetSecretValue.html).
 * The secret's ARN is {@code arn}, not the {@code aRN} a lower first letter makes of {@code ARN}:
 * "Before February 2024, some Secrets Manager operations reported events that contained "aRN"
 * instead of "arn" for the secret ARN" (the entries page). The result is null for a read-only
 * call, as CloudTrail's record contents give {@code responseElements} "For readOnly APIs, this
 * field is null", for a call that answers nothing and for a failed one. An error is recorded under
 * the {@code __type} the JSON protocol answers with ({@code ResourceNotFoundException}).
 *
 * <p>{@code BatchGetSecretValue} is recorded as one {@code BatchGetSecretValue} event: the entries
 * page lists the {@code GetSecretValue} entry as "Generated by the GetSecretValue and
 * BatchGetSecretValue operations" without saying how many, and the records a 2024 batch retrieval
 * left are {@code BatchGetSecretValue} events only.
 */
@ApplicationScoped
public class SecretsManagerCloudTrailEvents implements ManagementEventSource {

    private static final Logger LOG = Logger.getLogger(SecretsManagerCloudTrailEvents.class);
    private static final String SERVICE = "secretsmanager";
    private static final String EVENT_SOURCE = ServicePrincipals.of(SERVICE);

    private final CloudTrailService cloudTrail;
    private final AccountResolver accounts;
    private final CurrentVertxRequest currentRequest;
    private final ObjectMapper mapper;

    @Inject
    public SecretsManagerCloudTrailEvents(CloudTrailService cloudTrail, AccountResolver accounts,
                                          CurrentVertxRequest currentRequest, ObjectMapper mapper) {
        this.cloudTrail = cloudTrail;
        this.accounts = accounts;
        this.currentRequest = currentRequest;
        this.mapper = mapper;
    }

    /** Records the call {@code response} answered, or that failed with {@code error} when it is set. */
    void record(String action, JsonNode request, String region, String authorization, Response response,
                AwsException error) {
        CloudTrailEventCatalog catalog = CloudTrailEventCatalog.of(SERVICE);
        if (!catalog.isManagementEvent(action)) {
            return;
        }
        try {
            CloudTrailShapes shapes = CloudTrailShapes.of(SERVICE);
            String errorCode = error == null ? null : error.jsonType();
            String errorMessage = error == null ? null : error.getMessage();
            if (error == null && response != null && response.getEntity() instanceof AwsErrorResponse answered) {
                errorCode = answered.type();
                errorMessage = answered.message();
            }
            boolean succeeded = errorCode == null && response != null && response.getStatus() < 400;
            ObjectNode result = succeeded && !catalog.isReadOnly(action) && response.getEntity() != null
                    ? withSecretArn(shapes.result(action, mapper.valueToTree(response.getEntity()))) : null;
            cloudTrail.emitManagementEvent(event(action, shapes.requestParameters(action, request),
                    accounts.extractAccessKeyId(authorization), region, request(currentRequest.getCurrent()), result,
                    errorCode, errorMessage));
        } catch (RuntimeException e) {
            // The call is answered either way; a record that could not be written is logged, not raised.
            LOG.warnv(e, "Failed to record CloudTrail call {0}", action);
        }
    }

    @Override
    public String credentialScope() {
        return SERVICE;
    }

    /**
     * The record of a call IAM enforcement refused with {@code refusal} before Secrets Manager ran it,
     * with {@code "requestParameters": null} as AWS records an authorization refusal and the code and
     * message the refusal answered with; null for a call that is not a management event.
     */
    @Override
    public CloudTrailService.ManagementEventInput refused(String operation, String accessKeyId, String region,
                                                          RoutingContext routingContext, Response refusal) {
        if (!CloudTrailEventCatalog.of(SERVICE).isManagementEvent(operation)) {
            return null;
        }
        return event(operation, null, accessKeyId, region, request(routingContext), null, REFUSED,
                refusalMessage(refusal));
    }

    private ObjectNode withSecretArn(ObjectNode result) {
        if (result == null || !result.has("aRN")) {
            return result;
        }
        ObjectNode renamed = mapper.createObjectNode();
        result.properties().forEach(member -> renamed.set("aRN".equals(member.getKey()) ? "arn" : member.getKey(),
                member.getValue()));
        return renamed;
    }

    private static CloudTrailService.ManagementEventInput event(String action, ObjectNode requestParameters,
                                                                String accessKeyId, String region,
                                                                HttpServerRequest request, ObjectNode result,
                                                                String errorCode, String errorMessage) {
        String sourceIp = request == null ? null : RequestSourceAddress.of(request);
        String userAgent = request == null ? null : request.getHeader("User-Agent");
        return new CloudTrailService.ManagementEventInput(EVENT_SOURCE, action, region, accessKeyId,
                requestParameters, result, CloudTrailEventCatalog.of(SERVICE).isReadOnly(action), sourceIp,
                userAgent, null, errorCode, errorMessage);
    }

    private static HttpServerRequest request(RoutingContext routingContext) {
        return routingContext == null ? null : routingContext.request();
    }
}
